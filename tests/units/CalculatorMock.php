<?php

namespace mchojrin\testing\tests\units;

require_once __DIR__."/../../src/Calculator.php";

use atoum\atoum;
use \mchojrin\testing\Calculator as TestedClass;
use \mchojrin\testing\Multiplier;

/**
 * Showcase of atoum-next's mocking: Calculator's Multiplier collaborator is
 * replaced by an instance generated on the fly by newMockInstance().
 */
class CalculatorMock extends atoum\test
{
	/**
	 * atoum infers the tested class from the test class name, so point it
	 * explicitly at Calculator (CalculatorMock would resolve to nothing).
	 */
	public function getTestedClassName(): ?string {
		return TestedClass::class;
	}

	/**
	 * Stubbed collaborator: the Calculator must return the mock's value.
	 */
	public function test__addThenMultiply_with_stubbed_collaborator(): void {
		$this
			// Given a Calculator whose Multiplier is a mock generated by atoum...
			->given($multiplier = $this->newMockInstance(Multiplier::class))
			// and multiply() stubbed to return 42 instead of the real 8 * 2 = 16...
			->and($this->calling($multiplier)->multiply = 42)
			->then
				// Then the Calculator returns the collaborator's value, proving it delegates.
				->integer((new TestedClass($multiplier))->addThenMultiply(3, 5, 2))
					->isEqualTo(42)
				// and it called multiply() once with the summed argument (3 + 5) and the factor.
				->mock($multiplier)
					->call('multiply')
						->withArguments(8, 2)
						->once()
		;
	}

	/**
	 * Unstubbed collaborator: atoum's partial mock calls the real method.
	 */
	public function test__addThenMultiply_with_unstubbed_collaborator(): void {
		$this
			// Given a Calculator with an unstubbed Multiplier mock...
			->given($multiplier = $this->newMockInstance(Multiplier::class))
			->and($calculator = new TestedClass($multiplier))
			->then
				// Then the mock keeps atoum's default partial behaviour and calls the real multiply(): (3 + 5) * 2.
				->integer($calculator->addThenMultiply(3, 5, 2))
					->isEqualTo(16)
				// and the real call is still recorded with the expected arguments.
				->mock($multiplier)
					->call('multiply')
						->withArguments(8, 2)
						->once()
		;
	}
}
